#!/usr/bin/env bash
# One-shot Arch Linux installer for doorman.
#
#   sudo scripts/install.sh --vm --daily-user stan \
#       --helium /path/Helium.AppImage --create-admin --enforce --ttl 15m
#
# The default install sets up packages, the venv, Helium, the CA, the service
# user, both proxies, launchers, and desktop entries. It does NOT remove wheel
# or apply the firewall unless --remove-wheel / --enforce are passed.

set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PREFIX=/opt/doorman
CONF_DIR=/etc/doorman
STATE_DIR=/var/lib/doorman
LOG_DIR=/var/log/doorman
SERVICE_USER=doorman
ADMIN_USER="admin"
DAILY_USER="${SUDO_USER:-}"
HELIUM_SRC=""
HELIUM_DST="$PREFIX/Helium.AppImage"
BROWSER_PORT=8080
STRICT_PORT=8081
PROXY_PORTS=8080-8099

VM=0
UPGRADE=0
NO_UPGRADE=0
NO_TRUST=0
ASSUME_YES=0
DRY_RUN=0
DO_ADMIN=0
DO_ENFORCE=0
DO_REMOVE_WHEEL=0
DO_TRUST_CA=0
DO_UNINSTALL=0
FORCE=0
TTL=""

usage() {
    cat <<'EOF'
usage: install.sh [options]

options:
  --vm                    Arch VM defaults: --yes, --trust-ca; implies --upgrade
  --daily-user NAME       the restricted desktop user (default: $SUDO_USER)
  --admin NAME            create this admin user (default: admin)
  --create-admin          create the default admin user
  --helium PATH           Helium AppImage to install
  --enforce               apply the per-UID firewall and enable its unit
  --ttl DURATION          auto-revert enforcement after DURATION (e.g. 15m)
  --remove-wheel          remove the daily user from wheel (explicit!)
  --trust-ca              install the CA system-wide and in the daily NSS DB
  --no-trust-ca           do not install the CA (browser MITM will fail)
  --no-upgrade            with --vm, do not run pacman -Syu
  --force                 overwrite generated allowlists/config
  --dry-run               print commands without changing anything
  --yes, -y               pass --noconfirm to pacman
  --uninstall             remove units, launchers, CA, users, and /opt/doorman
  -h, --help              show this help

The default install does not remove wheel and does not apply the firewall.
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --vm) VM=1; shift ;;
        --daily-user) DAILY_USER="$2"; shift 2 ;;
        --admin) DO_ADMIN=1; ADMIN_USER="$2"; shift 2 ;;
        --create-admin) DO_ADMIN=1; shift ;;
        --helium) HELIUM_SRC="$2"; shift 2 ;;
        --enforce) DO_ENFORCE=1; shift ;;
        --no-enforce) DO_ENFORCE=0; shift ;;
        --ttl) TTL="$2"; shift 2 ;;
        --remove-wheel) DO_REMOVE_WHEEL=1; shift ;;
        --trust-ca) DO_TRUST_CA=1; shift ;;
        --no-trust-ca) NO_TRUST=1; DO_TRUST_CA=0; shift ;;
        --no-upgrade) NO_UPGRADE=1; UPGRADE=0; shift ;;
        --force) FORCE=1; shift ;;
        --dry-run) DRY_RUN=1; shift ;;
        --yes|-y) ASSUME_YES=1; shift ;;
        --uninstall) DO_UNINSTALL=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "unknown argument: $1" >&2; usage; exit 2 ;;
    esac
done

if [ "$VM" = 1 ]; then
    ASSUME_YES=1
    [ "$NO_TRUST" = 1 ] || DO_TRUST_CA=1
    [ "$NO_UPGRADE" = 1 ] || UPGRADE=1
fi

run() {
    if [ "$DRY_RUN" = 1 ]; then
        printf '+ '
        printf '%q ' "$@"
        printf '\n'
    else
        "$@"
    fi
}

write_file() {
    local path="$1" mode="${2:-644}"
    if [ "$DRY_RUN" = 1 ]; then
        echo "+ write $path"
        cat >/dev/null
    else
        mkdir -p "$(dirname "$path")"
        cat >"$path"
        chmod "$mode" "$path"
    fi
}

merge_allowlists() {
    local out="$1"; shift
    if [ "$DRY_RUN" = 1 ]; then
        echo "+ merge allowlists into $out"
        return
    fi
    mkdir -p "$(dirname "$out")"
    {
        echo "# generated by doorman installer; edit and restart doorman-strict"
        for f in "$@"; do
            [ -f "$f" ] || continue
            echo
            echo "# from $(basename "$f")"
            cat "$f"
        done
    } >"$out"
    chmod 644 "$out"
}

require_root() {
    if [ "$DRY_RUN" = 1 ]; then
        return 0
    fi
    if [ "$(id -u)" -ne 0 ]; then
        echo "run this with sudo: sudo $0 $*" >&2
        exit 1
    fi
}

update_ca_trust() {
    if command -v update-ca-trust >/dev/null 2>&1; then
        run update-ca-trust
    elif command -v trust >/dev/null 2>&1; then
        run trust extract-compat
    else
        echo "warning: no update-ca-trust or trust; system CA store not refreshed" >&2
    fi
}

nss_exec() {
    local home="$1"; shift
    run runuser -u "$DAILY_USER" -- env HOME="$home" "$@"
}

if [ ! -f /etc/arch-release ]; then
    echo "this installer targets Arch Linux (/etc/arch-release missing)" >&2
    exit 1
fi
if [ -z "$DAILY_USER" ]; then
    echo "pass --daily-user NAME (could not infer from SUDO_USER)" >&2
    exit 1
fi

require_root

if [ "$DO_UNINSTALL" = 1 ]; then
    echo "uninstalling doorman..." >&2
    run systemctl stop doorman-firewall-revert.timer 2>/dev/null || true
    run systemctl disable --now doorman-firewall.service doorman-strict.service \
        doorman-browser.service 2>/dev/null || true
    run nft delete table inet doorman 2>/dev/null || true

    run rm -f /etc/systemd/system/doorman-browser.service \
        /etc/systemd/system/doorman-strict.service \
        /etc/systemd/system/doorman-firewall.service
    run systemctl daemon-reload
    run rm -f /usr/local/bin/doorman-browser /usr/local/bin/doorman-run
    run rm -f /usr/share/applications/doorman-browser.desktop \
        /usr/share/applications/doorman-steam.desktop

    if [ -f /etc/ca-certificates/trust-source/anchors/doorman.crt ]; then
        run rm -f /etc/ca-certificates/trust-source/anchors/doorman.crt
        update_ca_trust
    fi
    DAILY_HOME="$(getent passwd "$DAILY_USER" | cut -d: -f6 || true)"
    if [ -n "$DAILY_HOME" ] && [ -d "$DAILY_HOME/.pki/nssdb" ]; then
        nss_exec "$DAILY_HOME" certutil -d "sql:$DAILY_HOME/.pki/nssdb" -D -n doorman 2>/dev/null || true
    fi

    run rm -rf "$CONF_DIR" "$PREFIX" "$LOG_DIR" "$STATE_DIR"
    run userdel "$SERVICE_USER" 2>/dev/null || true
    echo "uninstalled. admin and daily users were not touched." >&2
    exit 0
fi

if [ "$VM" = 1 ] && [ "$UPGRADE" = 1 ]; then
    run pacman -Syu --noconfirm
fi

PACMAN=(pacman -S --needed)
if [ "$ASSUME_YES" = 1 ]; then
    PACMAN+=(--noconfirm)
fi
run "${PACMAN[@]}" python nftables iproute2 nss ca-certificates openssl curl \
    sudo shadow systemd xdg-utils desktop-file-utils

if ! pacman -Q fuse2 >/dev/null 2>&1; then
    run pacman -S --needed --noconfirm fuse2 || \
        echo "warning: fuse2 not installed; use APPIMAGE_EXTRACT_AND_RUN=1 for Helium" >&2
fi

run install -d -m 755 "$PREFIX" "$CONF_DIR" "$LOG_DIR" "$STATE_DIR"
run install -d -m 755 "$PREFIX/scripts"

if [ ! -x "$PREFIX/.venv/bin/python" ]; then
    run python -m venv "$PREFIX/.venv"
fi
if [ ! -x "$PREFIX/.venv/bin/mitmdump" ]; then
    run "$PREFIX/.venv/bin/python" -m pip install --upgrade pip
    run "$PREFIX/.venv/bin/pip" install mitmproxy
fi

for f in addon.py strict_proxy.py rules.py allowlist.txt strict_allowlist.txt \
         steam_allowlist.txt; do
    if [ -f "$PROJECT_DIR/$f" ]; then
        run install -m 644 "$PROJECT_DIR/$f" "$PREFIX/$f"
    fi
done
run install -m 755 "$PROJECT_DIR/scripts/doorman-firewall.sh" "$PREFIX/scripts/doorman-firewall.sh"

if ! id "$SERVICE_USER" >/dev/null 2>&1; then
    run useradd --system --home "$STATE_DIR" --shell /usr/bin/nologin "$SERVICE_USER"
fi
if id "$SERVICE_USER" >/dev/null 2>&1; then
    SERVICE_GROUP="$(id -gn "$SERVICE_USER")"
else
    SERVICE_GROUP="$SERVICE_USER"
fi
run chown "$SERVICE_USER:$SERVICE_GROUP" "$STATE_DIR" "$LOG_DIR"
run install -d -m 700 -o "$SERVICE_USER" -g "$SERVICE_GROUP" "$STATE_DIR/mitmproxy"

if [ "$DO_ADMIN" = 1 ]; then
    if ! id "$ADMIN_USER" >/dev/null 2>&1; then
        run useradd -m -G wheel -s /bin/bash "$ADMIN_USER"
        run passwd "$ADMIN_USER"
    else
        run usermod -aG wheel "$ADMIN_USER"
    fi
    run sudo -l -U "$ADMIN_USER" || true
fi

if [ "$DO_REMOVE_WHEEL" = 1 ]; then
    if [ "$DRY_RUN" = 0 ]; then
        if ! id "$ADMIN_USER" >/dev/null 2>&1; then
            echo "--remove-wheel needs an existing --admin user" >&2
            exit 1
        fi
        if [ "$ADMIN_USER" = "$DAILY_USER" ]; then
            echo "admin and daily user must be different" >&2
            exit 1
        fi
        if ! sudo -l -U "$ADMIN_USER" >/dev/null 2>&1; then
            echo "$ADMIN_USER does not have working sudo; refusing to remove wheel" >&2
            exit 1
        fi
    fi
    run gpasswd -d "$DAILY_USER" wheel || true
    echo "remaining sudo rules for $DAILY_USER:" >&2
    run sudo -l -U "$DAILY_USER" || true
fi

if [ -n "$HELIUM_SRC" ]; then
    if [ ! -x "$HELIUM_SRC" ]; then
        echo "Helium AppImage is not executable: $HELIUM_SRC" >&2
        exit 1
    fi
    run install -m 755 "$HELIUM_SRC" "$HELIUM_DST"
elif [ ! -x "$HELIUM_DST" ]; then
    echo "no Helium AppImage: pass --helium /path/to/Helium.AppImage" >&2
    exit 1
fi
if [ "$DRY_RUN" = 0 ]; then
    sha256sum "$HELIUM_DST" >"$CONF_DIR/helium.sha256"
fi

CA_DIR="$STATE_DIR/mitmproxy"
CA_CERT="$CA_DIR/mitmproxy-ca-cert.pem"
if [ ! -f "$CA_CERT" ]; then
    if [ "$DRY_RUN" = 1 ]; then
        echo "+ generate mitmproxy CA in $CA_DIR"
    else
        install -d -m 700 -o "$SERVICE_USER" -g "$SERVICE_GROUP" "$CA_DIR"
        chown -R "$SERVICE_USER:$SERVICE_GROUP" "$CA_DIR"
        timeout 5 runuser -u "$SERVICE_USER" -- env HOME="$STATE_DIR" \
            "$PREFIX/.venv/bin/mitmdump" --set confdir="$CA_DIR" \
            --listen-host 127.0.0.1 --listen-port 18080 >/dev/null 2>&1 || true
    fi
fi
if [ "$DRY_RUN" = 0 ] && [ ! -f "$CA_CERT" ]; then
    echo "mitmproxy did not generate $CA_CERT" >&2
    exit 1
fi

if [ "$DO_TRUST_CA" = 1 ]; then
    run install -D -m 644 "$CA_CERT" /etc/ca-certificates/trust-source/anchors/doorman.crt
    update_ca_trust
    DAILY_HOME="$(getent passwd "$DAILY_USER" | cut -d: -f6 || true)"
    if [ -n "$DAILY_HOME" ]; then
        run runuser -u "$DAILY_USER" -- env HOME="$DAILY_HOME" mkdir -p "$DAILY_HOME/.pki/nssdb"
        nss_exec "$DAILY_HOME" certutil -d "sql:$DAILY_HOME/.pki/nssdb" -N --empty-password 2>/dev/null || true
        nss_exec "$DAILY_HOME" certutil -d "sql:$DAILY_HOME/.pki/nssdb" -D -n doorman 2>/dev/null || true
        nss_exec "$DAILY_HOME" certutil -d "sql:$DAILY_HOME/.pki/nssdb" -A -t "C,," -n doorman -i "$CA_CERT"
    fi
fi

if [ ! -f "$CONF_DIR/strict_allowlist.txt" ] || [ "$FORCE" = 1 ]; then
    merge_allowlists "$CONF_DIR/strict_allowlist.txt" \
        "$PROJECT_DIR/strict_allowlist.txt" \
        "$PROJECT_DIR/steam_allowlist.txt"
fi

write_file "$CONF_DIR/doorman.conf" 644 <<EOF
DAILY_USER=$DAILY_USER
DAILY_UID=$(id -u "$DAILY_USER")
SERVICE_USER=$SERVICE_USER
BROWSER_PORT=$BROWSER_PORT
STRICT_PORT=$STRICT_PORT
PROXY_PORTS=$PROXY_PORTS
HELIUM_APPIMAGE=$HELIUM_DST
CA_CERT=$CA_CERT
EOF

write_file /etc/systemd/system/doorman-browser.service 644 <<'EOF'
[Unit]
Description=doorman browser proxy (MITM)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=doorman
Group=doorman
ExecStart=/opt/doorman/.venv/bin/mitmdump --set confdir=/var/lib/doorman/mitmproxy -s /opt/doorman/addon.py --listen-host 127.0.0.1 --listen-port 8080
Restart=on-failure
RestartSec=2s
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=/var/lib/doorman

[Install]
WantedBy=multi-user.target
EOF

write_file /etc/systemd/system/doorman-strict.service 644 <<'EOF'
[Unit]
Description=doorman strict host allowlist proxy
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=doorman
Group=doorman
ExecStart=/opt/doorman/.venv/bin/python /opt/doorman/strict_proxy.py --listen-host 127.0.0.1 --listen-port 8081 --allowlist /etc/doorman/strict_allowlist.txt
Restart=on-failure
RestartSec=2s
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true

[Install]
WantedBy=multi-user.target
EOF

write_file /etc/systemd/system/doorman-firewall.service 644 <<EOF
[Unit]
Description=doorman per-UID firewall
After=network-online.target doorman-browser.service doorman-strict.service
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/opt/doorman/scripts/doorman-firewall.sh apply --mode drop --uid $(id -u "$DAILY_USER") --table doorman --proxy-ports $PROXY_PORTS
ExecStop=/opt/doorman/scripts/doorman-firewall.sh revert --table doorman

[Install]
WantedBy=multi-user.target
EOF

write_file /usr/local/bin/doorman-browser 755 <<'EOF'
#!/bin/sh
set -eu
APP="${DOORMAN_HELIUM_APPIMAGE:-/opt/doorman/Helium.AppImage}"
PROFILE="${DOORMAN_HELIUM_PROFILE:-$HOME/.config/doorman-helium}"
exec "$APP" --user-data-dir="$PROFILE" --proxy-server="http://127.0.0.1:8080" "$@"
EOF

write_file /usr/local/bin/doorman-run 755 <<'EOF'
#!/bin/sh
set -eu
if [ $# -lt 1 ]; then
    echo "usage: doorman-run <steam|command> [args...]" >&2
    exit 2
fi
app="$1"
shift
case "$app" in
    steam) cmd="${DOORMAN_STEAM_CMD:-steam}" ;;
    *) cmd="$app" ;;
esac
export http_proxy="http://127.0.0.1:8081"
export https_proxy="$http_proxy"
export HTTP_PROXY="$http_proxy"
export HTTPS_PROXY="$http_proxy"
export all_proxy="$http_proxy"
export ALL_PROXY="$http_proxy"
export no_proxy="localhost,127.0.0.1,::1"
export NO_PROXY="$no_proxy"
exec "$cmd" "$@"
EOF

write_file /usr/share/applications/doorman-browser.desktop 644 <<'EOF'
[Desktop Entry]
Type=Application
Name=Helium (doorman)
Comment=Helium through the doorman browser proxy
Exec=/usr/local/bin/doorman-browser %U
Terminal=false
Categories=Network;WebBrowser;
MimeType=x-scheme-handler/http;x-scheme-handler/https;
EOF

if command -v steam >/dev/null 2>&1; then
    write_file /usr/share/applications/doorman-steam.desktop 644 <<'EOF'
[Desktop Entry]
Type=Application
Name=Steam (doorman)
Comment=Steam through the doorman strict proxy
Exec=/usr/local/bin/doorman-run steam %U
Terminal=false
Categories=Game;
MimeType=x-scheme-handler/steam;
EOF
fi


if [ -f "$PROJECT_DIR/policy/internet-blocker.json" ]; then
    run install -d -m 755 /etc/chromium/policies/managed
    run install -m 644 "$PROJECT_DIR/policy/internet-blocker.json" \
        /etc/chromium/policies/managed/internet-blocker.json
fi

if command -v ss >/dev/null 2>&1; then
    for p in "$BROWSER_PORT" "$STRICT_PORT"; do
        if ss -ltnH "sport = :$p" | grep -q .; then
            echo "warning: port $p is already in use; the service may fail to start" >&2
        fi
    done
fi

run systemctl daemon-reload
run systemctl enable doorman-browser.service doorman-strict.service
run systemctl restart doorman-browser.service doorman-strict.service

if [ "$DO_ENFORCE" = 1 ]; then
    run systemctl enable doorman-firewall.service
    run systemctl restart doorman-firewall.service
    if [ -n "$TTL" ]; then
        run systemd-run --unit=doorman-firewall-revert --on-active="$TTL" \
            "$PREFIX/scripts/doorman-firewall.sh" revert --table doorman
        echo "firewall will auto-revert in $TTL. Cancel with:" >&2
        echo "  systemctl stop doorman-firewall-revert.timer" >&2
    fi
fi

if command -v update-desktop-database >/dev/null 2>&1; then
    run update-desktop-database /usr/share/applications
fi

if [ "$DRY_RUN" = 1 ]; then
    echo "DRY RUN: nothing was changed." >&2
else
    echo "doorman installed." >&2
fi

cat >&2 <<EOF

  browser : /usr/local/bin/doorman-browser  (Helium, proxy :$BROWSER_PORT)
  steam   : /usr/local/bin/doorman-run steam
  policy  : /etc/doorman/strict_allowlist.txt
  logs    : journalctl -u doorman-browser -u doorman-strict
  firewall: systemctl status doorman-firewall

The strict allowlist is merged from strict_allowlist.txt and steam_allowlist.txt
at install time. Edit /etc/doorman/strict_allowlist.txt and restart
doorman-strict after changes.

EOF

if [ "$DO_TRUST_CA" = 0 ]; then
    echo "warning: CA was not trusted; browser HTTPS will fail until --trust-ca is used" >&2
fi

cat >&2 <<EOF
To undo everything: sudo $0 --uninstall
EOF
